-- إعداد قاعدة بيانات صفحة إشعار تقرير الأعمال والإنطفاء لمشروع AZL
-- شغّل هذا الملف من Supabase SQL Editor داخل مشروع Supabase المخصص لـ AZL فقط.

create table if not exists public.work_notices (
  id bigint generated by default as identity primary key,
  region text not null check (char_length(trim(region)) between 1 and 100),
  work_name text not null check (work_name in ('عمل مجدول', 'عمل طارئ', 'صيانة')),
  department text not null check (department in ('الصيانة', 'الإنشاءات', 'الطواري', 'العمليات')),
  start_date date not null,
  start_time time without time zone not null,
  end_date date not null,
  end_time time without time zone not null,
  created_at timestamptz not null default now(),
  constraint work_notices_valid_period check (
    (end_date + end_time) >= (start_date + start_time)
  )
);

alter table public.work_notices enable row level security;

grant select, insert on public.work_notices to anon, authenticated;
grant usage, select on sequence public.work_notices_id_seq to anon, authenticated;

drop policy if exists "Anyone can view work notices" on public.work_notices;
create policy "Anyone can view work notices"
on public.work_notices for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can add work notices" on public.work_notices;
create policy "Anyone can add work notices"
on public.work_notices for insert
to anon, authenticated
with check (
  char_length(trim(region)) between 1 and 100
  and work_name in ('عمل مجدول', 'عمل طارئ', 'صيانة')
  and department in ('الصيانة', 'الإنشاءات', 'الطواري', 'العمليات')
  and (end_date + end_time) >= (start_date + start_time)
);

-- حذف جميع إشعارات الأسبوع السابق تلقائيًا كل جمعة الساعة 00:00 بتوقيت السعودية.
-- السعودية UTC+3، لذا الموعد المقابل هو الخميس 21:00 بالتوقيت العالمي (UTC).
create or replace function public.clear_work_notices_weekly()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.work_notices;
$$;

revoke all on function public.clear_work_notices_weekly() from public, anon, authenticated;

create extension if not exists pg_cron with schema pg_catalog;

do $$
begin
  if exists (select 1 from cron.job where jobname = 'clear-work-notices-weekly') then
    perform cron.unschedule(jobid)
    from cron.job
    where jobname = 'clear-work-notices-weekly';
  end if;

  perform cron.schedule(
    'clear-work-notices-weekly',
    '0 21 * * 4',
    'select public.clear_work_notices_weekly();'
  );
end
$$;

-- تفعيل تحديثات Realtime حتى تظهر الإشعارات الجديدة مباشرة لدى المستخدمين.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'work_notices'
  ) then
    alter publication supabase_realtime add table public.work_notices;
  end if;
end
$$;
